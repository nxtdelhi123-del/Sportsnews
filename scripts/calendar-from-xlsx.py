#!/usr/bin/env python3
"""Turn the content calendar spreadsheet into lib/studio/calendar-data.js.

    python3 -I scripts/calendar-from-xlsx.py path/to/calendar.xlsx

Keeps the Sports Binge (TSB) rows that have a clock time on the 'Calendar' sheet.
'Breaking (any time)' rows are the autopilot's normal job, and Story / Internal rows
are not feed posts, so they are left out. Needs openpyxl (pip install openpyxl).
"""
import datetime, json, re, sys
import openpyxl

def main(path, out='lib/studio/calendar-data.js'):
    ws = openpyxl.load_workbook(path, data_only=True)['Calendar']
    head = [str(c or '').strip() for c in next(ws.iter_rows(max_row=1, values_only=True))]
    col = {h: i for i, h in enumerate(head)}
    def get(r, name):
        v = r[col[name]] if name in col else None
        return '' if v is None else v
    slots, seen = [], set()
    for r in ws.iter_rows(min_row=2, values_only=True):
        if get(r, 'Brand') != 'TSB' or not isinstance(get(r, 'Date'), datetime.datetime):
            continue
        t = get(r, 'Time (IST)')
        if not isinstance(t, datetime.time):
            continue
        if str(get(r, 'Status')).strip() in ('Dropped', 'Posted'):
            continue
        date = get(r, 'Date').date().isoformat()
        hhmm = f'{t.hour:02d}:{t.minute:02d}'
        sid = f'{date}T{hhmm}'
        n = 2
        while sid in seen:
            sid = f'{date}T{hhmm}-{n}'; n += 1
        seen.add(sid)
        clean = lambda k: re.sub(r'\s+', ' ', str(get(r, k))).strip()
        slots.append({
            'id': sid, 'date': date, 'time': hhmm,
            'pillar': clean('Pillar'), 'format': clean('Format'), 'template': clean('Template'),
            'hook': clean('Post / hook'), 'verify': clean('Source to verify'), 'label': clean('Label on post'),
            'owner': clean('Owner'), 'approval': clean('Approval'), 'notes': clean('Notes'),
        })
    slots.sort(key=lambda s: (s['date'], s['time']))
    body = ',\n'.join('  ' + json.dumps(s, ensure_ascii=False) for s in slots)
    with open(out, 'w', encoding='utf-8') as f:
        f.write('// Generated by scripts/calendar-from-xlsx.py from the content calendar. Do not edit by hand:\n')
        f.write('// update the spreadsheet and run the script again. Times are IST.\n')
        f.write(f'export default [\n{body},\n];\n')
    print(f'{len(slots)} TSB slots, {slots[0]["date"]} to {slots[-1]["date"]} -> {out}')

if __name__ == '__main__':
    main(*sys.argv[1:])
